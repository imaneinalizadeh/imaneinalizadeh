"""
Attempt 2 Dataset Builder
Dataset: artnitolog/llm-generated-texts
Source: Reuters news headlines generated by various LLMs

Run this standalone to inspect and save the dataset before training.
Useful for understanding why Attempt 2 got F1 0.71 (better length match
than Attempt 1 but still some mismatch vs Fakeddit short titles).
"""

from datasets import load_dataset
import pandas as pd
import json, random, os

SAVE_PATH = "/content/drive/MyDrive/fakeddit/ai_attempt2_dataset.json"
SEED = 42
random.seed(SEED)

print("=" * 60)
print("ATTEMPT 2 DATASET: artnitolog/llm-generated-texts")
print("=" * 60)

# ── Load ──────────────────────────────────────────────────────
print("\nLoading dataset...")
ds = load_dataset("artnitolog/llm-generated-texts", split="train")
print(f"Total rows: {len(ds)}")
print(f"Columns: {ds.column_names}")

# ── Inspect ───────────────────────────────────────────────────
print("\nSample rows:")
for i, row in enumerate(ds.select(range(3))):
    print(f"\nRow {i}:")
    for k, v in row.items():
        val = str(v)[:120]
        print(f"  {k}: {val}")

# ── Extract texts ─────────────────────────────────────────────
print("\nExtracting texts...")
texts = []
lengths = []

for row in ds:
    text = row.get("text", "").strip()
    if not text:
        continue

    # Take first sentence — Reuters style is often multi-sentence
    first = text.split(".")[0].strip()
    if len(first) > 8:
        texts.append(first)
        lengths.append(len(first))

    # Also try splitting on newlines
    lines = [l.strip() for l in text.split("\n") if len(l.strip()) > 8]
    if lines:
        texts.append(lines[0])
        lengths.append(len(lines[0]))

texts = list(set(texts))
random.shuffle(texts)

print(f"\nExtracted: {len(texts):,} unique texts")

# ── Length analysis (key diagnostic) ─────────────────────────
print("\nLength distribution:")
short  = len([l for l in lengths if l < 50])
medium = len([l for l in lengths if 50 <= l < 100])
long   = len([l for l in lengths if l >= 100])
print(f"  < 50 chars:   {short:,}  ({short/len(lengths)*100:.1f}%)")
print(f"  50-100 chars: {medium:,}  ({medium/len(lengths)*100:.1f}%)")
print(f"  > 100 chars:  {long:,}  ({long/len(lengths)*100:.1f}%)")
print(f"  Avg length:   {sum(lengths)/len(lengths):.0f} chars")

# Compare to Fakeddit
print("\nNOTE: Fakeddit Reddit titles avg ~60 chars")
print("Reuters texts are longer on average → explains F1 0.71 not 0.90")
print("This is the domain mismatch identified in error analysis")

# ── Filter to best length range ────────────────────────────────
filtered = [t for t in texts if 15 < len(t) < 120]
print(f"\nAfter filtering (15-120 chars): {len(filtered):,}")

# Sample comparison with Fakeddit
print("\nSample Attempt 2 texts:")
for t in filtered[:10]:
    print(f"  ({len(t):3d}c) {t}")

# ── Save ──────────────────────────────────────────────────────
dataset = {
    "name":        "artnitolog/llm-generated-texts",
    "attempt":     2,
    "description": "Reuters headlines generated by LLMs. Better length match than Attempt 1 but still some mismatch vs Fakeddit short Reddit titles.",
    "result_f1":   0.71,
    "result_recall": 0.61,
    "total_texts": len(filtered),
    "texts":       filtered,
    "length_stats": {
        "mean":   sum(len(t) for t in filtered) / len(filtered),
        "min":    min(len(t) for t in filtered),
        "max":    max(len(t) for t in filtered),
    }
}

os.makedirs(os.path.dirname(SAVE_PATH), exist_ok=True)
with open(SAVE_PATH, "w") as f:
    json.dump(dataset, f)

print(f"\nSaved to: {SAVE_PATH}")
print(f"Total AI-Generated texts for Attempt 2: {len(filtered):,}")

# ── Download locally ──────────────────────────────────────────
from google.colab import files
local_save = "/content/ai_attempt2_dataset.json"
with open(local_save, "w") as f:
    json.dump(dataset, f)
files.download(local_save)
print("Downloaded locally.")
